#!/usr/bin/env python3
"""Generate/check the pinned migration worker from the reviewed runtime helpers.

The literal remains independently hash-pinned by update_worker_contracts.py.
Changing a source helper requires regenerating and reviewing this literal.
P-CD-08: the lease code and the shared SQLite layer of the workers are not copied into the literal; the generated
function composes them at run time from their single sources (Get-DomeniaStorageLeaseWorkerCode and
Get-DomeniaSqliteWorkerCommon), exactly like every storage worker. tools/Production.Source.ps1 mirrors this generator.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = json.loads((ROOT / 'tools/migration-worker.json').read_text(encoding='utf-8-sig'))
SOURCES = {row['File']: row['Functions'] for row in SPEC['Sources']}
HEADER = "# Generated by tools/update_migration_worker.py; review and pin after changes.\nfunction Get-DomeniaMigrationWorkerCode {\n"
PRELUDE = ("    # Lease code and shared SQLite layer of the workers, composed from their single sources (P-CD-08).\n"
           "    return (Get-DomeniaStorageLeaseWorkerCode)+[Environment]::NewLine+(Get-DomeniaSqliteWorkerCommon)+[Environment]::NewLine+@'\n")


def composed_definitions():
    """Names of the functions the worker receives from its composed parts: the lease code and the shared SQLite layer."""
    lease = (ROOT / 'wad/modules/Domenia-StorageLease.Model.ps1').read_text(encoding='utf-8-sig')
    storage = (ROOT / 'wad/modules/Domenia-Storage.Worker.ps1').read_text(encoding='utf-8-sig')
    common = re.search(r"(?ms)^function Get-DomeniaSqliteWorkerCommon \{.*?@'\n(.*?)\n^'@", storage)
    if not common:
        raise ValueError('Missing shared SQLite layer: Get-DomeniaSqliteWorkerCommon')
    return set(re.findall(r'(?m)^function (\S+)', lease + '\n' + common.group(1)))


def render():
    bodies = []
    for file, names in SOURCES.items():
        source = (ROOT / 'wad' / file).read_text(encoding='utf-8-sig')
        for name in names:
            match = re.search(r'^function ' + re.escape(name) + r'\s*\{.*?(?=^function |\Z)', source, re.M | re.S)
            if not match:
                raise ValueError('Missing helper: ' + file + ' / ' + name)
            # Top-level helpers end at a column-zero closing brace; following comments are not part of the body.
            body = match.group(0)
            end = body.rfind('\n}')
            if end < 0:
                first = body.splitlines()[0]
                if first.endswith('}'):
                    bodies.append(first)
                    continue
                raise ValueError('Missing closing brace: ' + name)
            bodies.append(body[:end + 2])
    body = '\n\n'.join(bodies) + SPEC['Tail']
    code = re.sub(r'(?m)^\s*#.*$', '', body)
    definitions = set(re.findall(r'^function (\S+)', code, re.M)) | composed_definitions()
    references = set(re.findall(r'\b([A-Za-z]+-Domenia[A-Za-z0-9]+)\b', code))
    missing = references - definitions
    if missing:
        raise ValueError('Worker helper dependencies missing: ' + ', '.join(sorted(missing)))
    return HEADER + PRELUDE + body + "'@\n}\n"

if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--apply', action='store_true')
    args = ap.parse_args()
    path = ROOT / 'wad/modules/Domenia-Migration.Worker.ps1'
    expected = b'\xef\xbb\xbf' + render().encode('utf-8')
    if args.apply:
        path.write_bytes(expected)
    if not path.exists() or path.read_bytes() != expected:
        raise SystemExit('Migration worker differs from its sources; review then use --apply.')
    print('PASS: migration worker matches its runtime helpers.')
