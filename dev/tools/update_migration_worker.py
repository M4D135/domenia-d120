#!/usr/bin/env python3
"""Generate/check the pinned migration worker from the reviewed runtime helpers.

The literal remains independently hash-pinned by update_worker_contracts.py.
Changing a source helper requires regenerating and reviewing this literal.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = json.loads((ROOT / 'tools/migration-worker.json').read_text(encoding='utf-8-sig'))
SOURCES = {row['File']: row['Functions'] for row in SPEC['Sources']}

def render():
    bodies = []
    for file, names in SOURCES.items():
        source = (ROOT / 'wad' / file).read_text(encoding='utf-8-sig')
        for name in names:
            match = re.search(r'^function ' + re.escape(name) + r'\s*\{.*?(?=^function |\Z)', source, re.M | re.S)
            if not match:
                raise ValueError('Missing helper: ' + file + ' / ' + name)
            # Top-level helpers end at a column-zero closing brace; following comments are not part of the body.
            body = match.group(0)
            end = body.rfind('\n}')
            if end < 0:
                first = body.splitlines()[0]
                if first.endswith('}'):
                    bodies.append(first)
                    continue
                raise ValueError('Missing closing brace: ' + name)
            bodies.append(body[:end + 2])
    body = '\n\n'.join(bodies) + SPEC['Tail']
    code = re.sub(r'(?m)^\s*#.*$', '', body)
    definitions = set(re.findall(r'^function (\S+)', code, re.M))
    references = set(re.findall(r'\b([A-Za-z]+-Domenia[A-Za-z0-9]+)\b', code))
    # A call guarded by ${function:Name} is optional: the worker skips it when the helper is not composed in.
    guarded = set(re.findall(r'\$\{function:([A-Za-z]+-Domenia[A-Za-z0-9]+)\}', code))
    missing = references - definitions - guarded
    if missing:
        raise ValueError('Worker helper dependencies missing: ' + ', '.join(sorted(missing)))
    return "# Generated by tools/update_migration_worker.py; review and pin after changes.\nfunction Get-DomeniaMigrationWorkerCode {\nreturn @'\n" + body + "'@\n}\n"

if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--apply', action='store_true')
    args = ap.parse_args()
    path = ROOT / 'wad/modules/Domenia-Migration.Worker.ps1'
    expected = b'\xef\xbb\xbf' + render().encode('utf-8')
    if args.apply:
        path.write_bytes(expected)
    if not path.exists() or path.read_bytes() != expected:
        raise SystemExit('Migration worker differs from its sources; review then use --apply.')
    print('PASS: migration worker matches its runtime helpers.')
